const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {webcrypto}=require('node:crypto');
const data=new Map(),sessions=new Map();
const storage=map=>({getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,String(v)),removeItem:k=>map.delete(k)});
const context={window:{},localStorage:storage(data),sessionStorage:storage(sessions),crypto:webcrypto,TextEncoder};
vm.createContext(context);
vm.runInContext(fs.readFileSync('src/assets/admin-preview-service.js','utf8'),context);
const create=context.window.AcademyAdminPreviewService.create;
const ids=course=>[...(course||[]).map(c=>c.id)];
(async()=>{
 const master=create(),staff=create(),student=create();
 await master.startAdmin();
 const before={id:'course-electrics',name:'Elétrica Básica',status:'published',format:'series',description:'Curso publicado',lessons:[{id:'lesson-1',name:'Circuitos elétricos',url:''}]};
 await master.writeCatalog([before],0);
 await assert.rejects(master.createContentAdmin('Instrutor QA','funcionario@contrem.example','curta'),/8 e 128/);
 await assert.rejects(master.createContentAdmin('','funcionario@contrem.example','SenhaForte123!'),/nome e e-mail/);
 const created=await master.createContentAdmin('Instrutor QA','funcionario@contrem.example','SenhaForte123!');
 assert.equal(created.active,true);
 assert.equal((await master.listStaff())[0].email,'funcionario@contrem.example');
 assert.equal('passwordHash' in (await master.listStaff())[0],false,'Nunca divulgar senha ou hash no painel');
 const disk=JSON.stringify(JSON.parse(data.get('contrem-adm-preview-db-v1')));
 assert.equal(disk.includes('SenhaForte123!'),false,'Nunca salvar senha em texto puro');
 assert.equal(disk.includes('inviteHash'),false,'Não criar convite ou token');
 await assert.rejects(master.createContentAdmin('Outro','FUNCIONARIO@CONTREM.EXAMPLE','OutraSenha123!'),/já existe uma conta/i);
 await assert.rejects(staff.signIn('funcionario@contrem.example','senha-incorreta'),/senha de teste/i);
 const authenticated=await staff.signIn('FUNCIONARIO@CONTREM.EXAMPLE','SenhaForte123!');
 assert.equal(authenticated.member.role,'content_admin');
 assert.equal(authenticated.member.display_name,'Instrutor QA');
 await assert.rejects(staff.listStaff(),/restrito/);
 await assert.rejects(staff.createContentAdmin('Outro','outro@contrem.example','SenhaForte123!'),/restrito/);
 await assert.rejects(staff.createStudent('Pessoa','outra@contrem.example','SenhaForte123!'),/restrito/);
 await assert.rejects(staff.setStudentActive('x',false),/restrito/);
 const first=(await staff.reload()).catalog;
 const newCourse={id:'course-hydraulics',name:'Hidráulica Básica',status:'draft',format:'series',description:'Novo conteúdo',lessons:[{id:'lesson-2',name:'Bombas',url:''}]};
 await assert.rejects(staff.writeCatalog([before,{...newCourse,status:'published'}],first.revision),/Somente o ADM Master publica/);
 await staff.writeCatalog([before,newCourse],first.revision);
 let after=(await staff.reload()).catalog;
 assert.equal(after.courses.length,2);
 await assert.rejects(staff.writeCatalog([newCourse],after.revision),/não pode excluir cursos/);
 await assert.rejects(staff.writeCatalog([before,{...newCourse,lessons:[]}],after.revision),/não pode excluir aulas/);
 await assert.rejects(staff.writeCatalog([{...before,name:'Alteração publicada!'},newCourse],after.revision),/rascunho/);
 const edited={...before,name:'Elétrica revisada',status:'draft',lessons:[...before.lessons,{id:'lesson-extra',name:'Medições',url:''}]};
 await staff.writeCatalog([edited,newCourse],after.revision);
 let published=JSON.parse(data.get('contrem-adm-preview-db-v1')).catalog.courses;
 assert.equal(published[0].name,'Elétrica Básica','staff edit must not change published course');
 const studentData=await master.createStudent('Aluno de Formação','aluno@contrem.example','SenhaAluno123!');
 const roster=await staff.listStudents();
 assert.equal(roster.members.some(m=>m.display_name==='Aluno de Formação'),true);
 const member=roster.members.find(m=>m.display_name==='Aluno de Formação');
 await staff.setCourseAccess(member.id,'course-electrics',true);
 await assert.rejects(staff.setStudentActive(member.id,false),/restrito/);
 const learner=await student.signIn('aluno@contrem.example','SenhaAluno123!');
 assert.equal(learner.catalog.courses[0].name,'Elétrica Básica');
 assert.equal(learner.catalog.courses.length,1);
 await assert.rejects(student.writeCatalog([],0),/restrito/);
 await master.startAdmin();
 const draft=(await master.reload()).catalog;
 const pending=draft.courses.find(c=>c.id==='course-electrics');
 assert.equal(pending.name,'Elétrica revisada');
 // Salvar outro rascunho não pode publicar uma revisão pendente.
 await master.writeCatalog([...draft.courses,{id:'course-diesel',name:'Diesel',status:'draft',lessons:[]}],draft.revision);
 assert.equal(JSON.parse(data.get('contrem-adm-preview-db-v1')).catalog.courses.find(c=>c.id==='course-electrics').name,'Elétrica Básica');
 const approved=(await master.reload()).catalog;
 await master.writeCatalog(approved.courses.map(c=>c.id==='course-electrics'?{...c,status:'published'}:c),approved.revision);
 await student.reload();
 assert.equal((await student.reload()).catalog.courses[0].name,'Elétrica revisada','master approval publishes pending edit');
 await master.setStaffActive((await master.listStaff())[0].id,false);
 await assert.rejects(staff.reload(),/desativado/);
 await assert.rejects(staff.signIn('funcionario@contrem.example','SenhaForte123!'),/desativado/);
 assert.equal((await master.listStaff())[0].active,false);
 assert.ok([...data.keys()].every(k=>k.startsWith('contrem-adm-preview')),'preview must not write production storage');
 console.log('PASS content-admin: direct login with name, email and password, permissions, draft isolation, master publishing, course and lesson delete denial, grants and deactivation');
})().catch(e=>{console.error(e);process.exitCode=1});
